# ввод суммы годового дохода
name = float(input("Введите ваш годовой доход: "))
# процент ставки налога
name1 = 0.13
# подсчет налога
name2 = name * name1
# после вычета налога
name3 = name - name2
# вывод всех цифр
print(f"Сумма дохода: {name:,.2f} руб.")
print(f"Сумма налога: {name2:,.2f} руб.")
print(f"Сумма (на руки) после вычета налога: {name3:,.2f} руб.")
