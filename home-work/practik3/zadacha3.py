num1 = input("введите 1 число: ")
num2 = input("введите 2 число: ")
#записываем числа для дальнейшего складывания
try:
    num1 = int(num1)
    num2 = int(num2)
    #переводим из текстового в целочисленное значение
    print("Сумма:", num1 + num2)
    #складываем числа

except ValueError:
    # если допустили какую то ошибку, которая препятствует операции сложения
    print("Ошибка! Вводить можно только целые числа!")
