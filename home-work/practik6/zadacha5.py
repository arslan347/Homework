# спрашиваем координаты
a = int(input("Столбец первой клетки: "))
b = int(input("Строка первой клетки: "))
c = int(input("Столбец второй клетки: "))
d = int(input("Строка второй клетки: "))

# проверяем что всё в пределах доски
if a < 1 or a > 8 or b < 1 or b > 8 or c > 8 or c < 1 or d < 1 or d > 8:
    print("Ошибка ввода")
# ферзь бьёт по строке, столбцу или диагонали
elif a == c or b == d or abs(a - c) == abs(b - d):
    print("YES")
else:
    print("NO")
